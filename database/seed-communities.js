async function seed() {
  const connection = await mysql.createConnection({
    host: process.env.DB_HOST || 'localhost',
    port: process.env.DB_PORT || 3306,
    user: process.env.DB_USER || 'root',
    password: process.env.DB_PASSWORD || '',
    database: process.env.DB_NAME || 'authentic_holiday_homes',
    multipleStatements: true
  });

  const migration = fs.readFileSync(path.join(__dirname, 'migration-communities.sql'), 'utf8');
  await connection.query(migration);

  const [existing] = await connection.query('SELECT COUNT(*) AS cnt FROM communities');
  if (existing[0].cnt > 0) { console.log(`Communities table already has ${existing[0].cnt} rows — skipping insert`); await connection.end(); return; }

  const insertSQL = 'INSERT IGNORE INTO communities (code, name, sector_number, sector) VALUES ?';
  const values = communities.map(c => [c.code, c.name, c.sector_number, c.sector]);
  await connection.query(insertSQL, [values]);

  console.log(`Seeded ${communities.length} communities`);
  await connection.end();
}

seed().catch(err => { console.error('Seed error:', err); process.exit(1); });
